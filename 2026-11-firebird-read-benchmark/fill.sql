-- Creates the benchmark table and fills it with 2,000,000 rows (Firebird 4 or newer).
-- Expected checksums: SUM(ID) = 2000001000000, SUM(PRICE) = 6900000.00.
CREATE TABLE BENCH_ROWS (
  ID BIGINT NOT NULL PRIMARY KEY,
  PARENT_ID INTEGER NOT NULL,
  BRANCH_NO INTEGER,
  KIND CHAR(1),
  STATUS CHAR(1),
  PRICE NUMERIC(18,2),
  OLD_PRICE NUMERIC(18,2),
  FACTOR DOUBLE PRECISION,
  LABEL_TEXT VARCHAR(200) CHARACTER SET UTF8,
  CREATED_AT TIMESTAMP,
  BIG_AMOUNT INT128,
  CREATED_TZ TIMESTAMP WITH TIME ZONE
);
COMMIT;
SET TERM ^;
EXECUTE BLOCK AS
DECLARE I BIGINT = 1;
BEGIN
  WHILE (I <= 2000000) DO
  BEGIN
    INSERT INTO BENCH_ROWS VALUES (:I, :I / 3, MOD(:I, 500), 'K', IIF(MOD(:I, 3) = 0, 'W', 'L'),
      1.5 + MOD(:I, 400) / 100.0, NULL, 1.0, 'Grüße aus Österreich, Zeile ' || :I,
      DATEADD(:I SECOND TO TIMESTAMP '2025-01-01 00:00:00'), :I * 1000000000000, CURRENT_TIMESTAMP);
    I = I + 1;
  END
END^
SET TERM ;^
COMMIT;
SELECT COUNT(*), SUM(ID), SUM(PRICE) FROM BENCH_ROWS;
