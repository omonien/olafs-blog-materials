-- Creates the benchmark table in SQL Server 2022 and fills it with the same 2,000,000 rows as firebird/fill.sql.
-- Strings are NVARCHAR (UTF-16), the native Unicode type of SQL Server.
-- Expected checksums: SUM(ID) = 2000001000000, SUM(PRICE) = 6900000.00.
CREATE DATABASE bench;
GO
ALTER DATABASE bench SET ALLOW_SNAPSHOT_ISOLATION ON;
GO
USE bench;
GO
CREATE TABLE BENCH_ROWS (
  ID BIGINT NOT NULL PRIMARY KEY,
  PARENT_ID INT NOT NULL,
  BRANCH_NO INT,
  KIND NCHAR(1),
  STATUS NCHAR(1),
  PRICE DECIMAL(18,2),
  OLD_PRICE DECIMAL(18,2),
  FACTOR FLOAT,
  LABEL_TEXT NVARCHAR(200),
  CREATED_AT DATETIME2(3),
  BIG_AMOUNT DECIMAL(38,0),
  CREATED_TZ DATETIMEOFFSET(3)
);
GO
INSERT INTO BENCH_ROWS WITH (TABLOCK)
SELECT value, value / 3, value % 500, N'K', CASE WHEN value % 3 = 0 THEN N'W' ELSE N'L' END,
       1.5 + ROUND((value % 400) / 100.0, 1, 1), NULL, 1.0,
       N'Grüße aus Österreich, Zeile ' + CAST(value AS NVARCHAR(20)),
       DATEADD(SECOND, CAST(value AS INT), CAST('2025-01-01T00:00:00' AS DATETIME2(3))),
       CAST(value AS DECIMAL(38,0)) * 1000000000000, SYSDATETIMEOFFSET()
FROM GENERATE_SERIES(CAST(1 AS BIGINT), CAST(2000000 AS BIGINT));
GO
SELECT COUNT(*), SUM(ID), SUM(PRICE) FROM BENCH_ROWS;
GO
